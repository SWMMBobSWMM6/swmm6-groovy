// Cs2Groovy - translate the generated C# SWMM6 engine (cs/gen) into Groovy 3 with static compilation
// (groovy/gen/engine), using Roslyn's semantic model. It is the Java translator (Cs2Java.cs, JavaTypes.cs, JavaFn.cs)
// copied and changed where Groovy reads Java's syntax differently: the same names, the same runtime calls (the Groovy
// runtime, groovy/src/cpp, has the Java runtime's shape) and the same analysis. The mapping is recorded in GROOVY.md.
//
//   dotnet bin/cs2groovy.dll CS_DIR GROOVY_GEN_DIR
//
// Written by Claude (Anthropic) for Robert Dickinson's SWMM6 ports; see AI-USE.md and groovy/README.md.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

public sealed class Todo : Exception { public Todo(string m) : base(m) { } }

public static partial class Cs2Groovy
{
    static CSharpCompilation comp = null!;
    static readonly Dictionary<SyntaxTree, SemanticModel> models = new();
    static SemanticModel M(SyntaxNode n) => models[n.SyntaxTree];
    static readonly SortedDictionary<string, int> todos = new();
    static readonly SortedDictionary<string, string> manifest = new();   // runtime member used -> its Java name

    public static int Main(string[] args)
    {
        var cs = args[0];
        var outDir = args[1];
        var files = Directory.GetFiles(Path.Combine(cs, "gen"), "*.cs").Concat(Directory.GetFiles(Path.Combine(cs, "runtime"), "*.cs"))
            .Where(f => !f.EndsWith("Program.cs")).OrderBy(f => f, StringComparer.Ordinal).ToArray();
        var opts = new CSharpParseOptions(LanguageVersion.Latest);
        var trees = files.Select(f => CSharpSyntaxTree.ParseText(File.ReadAllText(f), opts, f)).ToList();
        var fw = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        var refs = new List<MetadataReference>();
        foreach (var f in Directory.GetFiles(fw, "*.dll"))
        {
            var b = Path.GetFileName(f);
            if (b.StartsWith("Microsoft.VisualBasic") || b == "mscorlib.dll") continue;
            try { refs.Add(MetadataReference.CreateFromFile(f)); } catch { }
        }
        comp = CSharpCompilation.Create("engine", trees, refs, new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errs = comp.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
        if (errs.Count > 0) { foreach (var e in errs.Take(10)) Console.Error.WriteLine(e); return 1; }
        foreach (var t in trees) models[t] = comp.GetSemanticModel(t);
        var gen = trees.Where(t => t.FilePath.Contains("/gen/") || Path.GetFileName(t.FilePath).StartsWith("Hand_")).ToList();

        var pkgDir = Path.Combine(outDir, "engine");
        Directory.CreateDirectory(pkgDir);
        foreach (var f in Directory.GetFiles(pkgDir, "*.groovy")) File.Delete(f);
        CollectTypes(gen);
        foreach (var g in engineTypes.GroupBy(TypeIdent).Where(g => g.Count() > 1)) Note("two types named " + g.Key);
        Analyze(gen);
        foreach (var s in engineTypes)
        {
            var sb = new StringBuilder();
            sb.Append(FileHeader);
            try { TypeDecl(s, sb); }
            catch (Todo e) { sb.Append("// TODO ").Append(e.Message).Append('\n'); }
            File.WriteAllText(Path.Combine(pkgDir, TypeIdent(s) + ".groovy"), sb.ToString());
        }
        foreach (var kv in extraFiles) File.WriteAllText(Path.Combine(pkgDir, kv.Key + ".groovy"), kv.Value);
        using (var w = new StreamWriter(Path.Combine(outDir, "..", "cs2groovy_todo.txt")))
            foreach (var kv in todos.OrderByDescending(kv => kv.Value)) w.WriteLine("{0,6}  {1}", kv.Value, kv.Key);
        using (var w = new StreamWriter(Path.Combine(outDir, "..", "cs2groovy_runtime.txt")))
            foreach (var kv in manifest) w.WriteLine(kv.Key + "\t" + kv.Value);
        Console.WriteLine("wrote " + Directory.GetFiles(pkgDir, "*.groovy").Length + " files, " + todos.Count + " TODO kinds, " + todos.Values.Sum() + " TODO sites");
        return 0;
    }

    static readonly SortedDictionary<string, string> extraFiles = new();

    public const string FileHeader = "// Code generated by tools/cs2x/Cs2Groovy.cs from cs/gen. DO NOT EDIT.\n\npackage engine\n\n";

    static void Note(string what) { todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1; }

    static string Todo(string what)
    {
        todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1;
        throw new Todo(what);
    }

    static void Use(string key, string java) { manifest[key] = java; }

    // ------------------------------------------------------------------------------------------------ names
    static readonly HashSet<string> GvReserved = new()
    {
        "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue",
        "default", "do", "double", "else", "enum", "extends", "final", "finally", "float", "for", "goto", "if",
        "implements", "import", "instanceof", "int", "interface", "long", "native", "new", "package", "private",
        "protected", "public", "return", "short", "static", "strictfp", "super", "switch", "synchronized", "this",
        "throw", "throws", "transient", "try", "void", "volatile", "while", "true", "false", "null", "var", "yield",
        "record", "sealed", "permits", "non", "_", "cpp", "engine", "java",
        // Groovy's keywords and the names it gives a meaning (it is a closure's parameter)
        "in", "as", "def", "trait", "it", "groovy", "threadsafe"
    };

    /// <summary>A runtime member's name as the Groovy runtime spells it: a Groovy keyword gets an underscore (groovy/tools/J2Gv.java
    /// renames Ios.in and R.as the same way).</summary>
    static readonly HashSet<string> GvKw = new() { "in", "as", "def", "trait", "it" };
    static string RtName(string n) => GvKw.Contains(n) ? n + "_" : n;

    // java.lang's simple names: an engine type must not hide one the translation uses
    static readonly HashSet<string> JavaLangTypes = new()
    {
        "String", "Object", "Math", "StrictMath", "Integer", "Long", "Double", "Float", "Short", "Byte", "Character",
        "Boolean", "Number", "System", "Runtime", "Thread", "Error", "Exception", "RuntimeException", "Throwable",
        "Class", "Iterable", "Override", "Record", "Void", "Enum", "Process", "Module", "Package", "Comparable",
        "Cloneable", "Deprecated", "IllegalStateException", "ArithmeticException", "ClassCastException",
        "SuppressWarnings", "FunctionalInterface", "SafeVarargs", "StringBuilder", "CharSequence", "Readable",
        "Appendable", "AutoCloseable", "Runnable", "ThreadLocal", "InheritableThreadLocal", "ClassLoader",
        "SecurityManager", "StackTraceElement", "ProcessBuilder", "Compiler", "Character", "Iterator"
    };

    static string Id(string n)
    {
        n = n.TrimStart('@');
        if (n.Contains('<') || n.Contains('>')) n = n.Replace("<", "_").Replace(">", "_");
        return GvReserved.Contains(n) ? n + "_" : n;
    }

    static bool IsRuntime(ISymbol s)
    {
        var ns = s is INamespaceSymbol nss ? nss : s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace)
        {
            if (ns.Name == "Cpp" && ns.ContainingNamespace.IsGlobalNamespace) return true;
            ns = ns.ContainingNamespace;
        }
        return false;
    }

    static bool IsSystem(ISymbol s)
    {
        var ns = s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace) { if (ns.Name == "System" && ns.ContainingNamespace.IsGlobalNamespace) return true; ns = ns.ContainingNamespace; }
        return false;
    }

    static readonly Dictionary<ISymbol, string> typeNames = new(SymbolEqualityComparer.Default);

    /// <summary>The Java class name of an engine type: its namespace below openswmm and its class nesting, joined by _.</summary>
    static string TypeIdent(INamedTypeSymbol t)
    {
        t = t.OriginalDefinition;
        if (typeNames.TryGetValue(t, out var n)) return n;
        var parts = new List<string>();
        for (var c = t; c != null; c = c.ContainingType) parts.Insert(0, c.Name);
        var ns = new List<string>();
        for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) ns.Insert(0, x.Name);
        if (ns.Count > 0 && (ns[0] == "openswmm" || ns[0] == "_global" || ns[0] == "Gen")) ns.RemoveAt(0);
        var s = string.Join("_", ns.Concat(parts));
        if (t.Name == "_F" && t.ContainingType == null)
        {
            // the free functions of a namespace: openswmm's are F_, the global namespace's F__global, others F_ns
            var full = new List<string>();
            for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) full.Insert(0, x.Name);
            s = full.Count == 1 && full[0] == "openswmm" ? "F_" : full.Count > 0 && full[0] == "openswmm" ? "F_" + string.Join("_", full.Skip(1)) : "F_" + string.Join("_", full);
        }
        if (GvReserved.Contains(s) || JavaLangTypes.Contains(s)) s += "_";
        // Groovy 3's grammar reads a declaration whose return type starts with a lower-case letter or _ (io_X m() { })
        // as a command expression: such a type is L + its Java name (io_X is Lio_X)
        if (!char.IsUpper(s[0])) s = "L" + s;
        typeNames[t] = s;
        return s;
    }

    static readonly Dictionary<IMethodSymbol, string> methodNames = new(SymbolEqualityComparer.Default);

    /// <summary>An engine method's Java name: overloads in one class, or across a hierarchy where C# hides a
    /// method Java would override, get a suffix of their parameter types (the rule Cs2Go uses).</summary>
    static string MethodIdent(IMethodSymbol m)
    {
        m = m.OriginalDefinition;
        if (m.OverriddenMethod != null) return MethodIdent(m.OverriddenMethod);
        if (methodNames.TryGetValue(m, out var n)) return n;
        var t = m.ContainingType;
        var same = t.GetMembers(m.Name).OfType<IMethodSymbol>().Where(x => x.MethodKind == MethodKind.Ordinary).ToList();
        var nm = m.Name.TrimStart('@');
        // a method implementing a runtime interface (ICopy.Clone/Assign, IHashFn.HashOf, IDisposable.Dispose, ...)
        // keeps the interface's name: Java overloads Assign(Base) and Assign(Derived) as C# does
        if (!m.IsStatic && ImplementsRuntimeInterface(m)) { methodNames[m] = nm; return nm; }
        bool overloaded = same.Count > 1;
        if (!overloaded && !m.IsStatic)
        {
            for (var b = t.BaseType; b != null && !IsSystem(b); b = b.BaseType)
                if (b.GetMembers(m.Name).OfType<IMethodSymbol>().Any(x => !SymbolEqualityComparer.Default.Equals(x, m) && x.MethodKind == MethodKind.Ordinary && !IsOverrideOf(m, x)))
                { overloaded = true; break; }
            // a derived class's method of the same name that does not override this one
            if (!overloaded && !(m.IsVirtual || m.IsAbstract))
                foreach (var d in engineTypes)
                    if (Derives(d, t) && d.GetMembers(m.Name).OfType<IMethodSymbol>().Any(x => x.MethodKind == MethodKind.Ordinary && !IsOverrideOf(x, m)))
                    { overloaded = true; break; }
        }
        if (overloaded && !(m.IsVirtual || m.IsAbstract))
            nm += "__" + string.Join("_", m.Parameters.Select(p => ShortType(p.Type) + (p.RefKind != RefKind.None ? "r" : "")));
        // a method that hides one of the same signature in a base or derived class (C#'s non-virtual __init_d in
        // each class of a hierarchy) would override it in Java: the class name keeps them apart
        if (!m.IsStatic && !(m.IsVirtual || m.IsAbstract || m.IsOverride) && HidesOrIsHidden(m)) nm += "_" + TypeIdent(t);
        if (GvReserved.Contains(nm) || nm == "getClass" || nm == "hashCode" || nm == "equals" || nm == "toString" || nm == "clone" ||
            nm == "finalize" || nm == "wait" || nm == "notify" || nm == "notifyAll") nm += "_";
        methodNames[m] = nm;
        return nm;
    }

    static bool SameSignature(IMethodSymbol a, IMethodSymbol b) =>
        a.Name == b.Name && a.Parameters.Length == b.Parameters.Length &&
        a.Parameters.Zip(b.Parameters).All(p => SymbolEqualityComparer.Default.Equals(p.First.Type, p.Second.Type) && p.First.RefKind == p.Second.RefKind);

    static bool HidesOrIsHidden(IMethodSymbol m)
    {
        var t = m.ContainingType;
        for (var b = t.BaseType; b != null && !IsSystem(b); b = b.BaseType)
            if (b.GetMembers(m.Name).OfType<IMethodSymbol>().Any(x => x.MethodKind == MethodKind.Ordinary && !x.IsStatic && SameSignature(x, m))) return true;
        foreach (var d in engineTypes)
            if (Derives(d, t) && d.GetMembers(m.Name).OfType<IMethodSymbol>().Any(x => x.MethodKind == MethodKind.Ordinary && !x.IsStatic && SameSignature(x, m) && !IsOverrideOf(x, m)))
                return true;
        return false;
    }

    static bool ImplementsRuntimeInterface(IMethodSymbol m)
    {
        foreach (var i in m.ContainingType.AllInterfaces)
        {
            if (!(IsRuntime(i) || IsSystem(i))) continue;
            foreach (var im in i.GetMembers().OfType<IMethodSymbol>())
                if (SymbolEqualityComparer.Default.Equals(m.ContainingType.FindImplementationForInterfaceMember(im), m)) return true;
        }
        return false;
    }

    static bool IsOverrideOf(IMethodSymbol m, IMethodSymbol b)
    {
        for (var o = m.OverriddenMethod; o != null; o = o.OverriddenMethod) if (SymbolEqualityComparer.Default.Equals(o.OriginalDefinition, b.OriginalDefinition)) return true;
        return false;
    }

    static bool Derives(INamedTypeSymbol d, INamedTypeSymbol b)
    {
        for (var x = d.BaseType; x != null; x = x.BaseType) if (SymbolEqualityComparer.Default.Equals(x.OriginalDefinition, b.OriginalDefinition)) return true;
        return false;
    }

    static string ShortType(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Int32: return "i";
            case SpecialType.System_Int64: return "l";
            case SpecialType.System_UInt64: return "ul";
            case SpecialType.System_UInt32: return "u";
            case SpecialType.System_Double: return "d";
            case SpecialType.System_Single: return "f";
            case SpecialType.System_Boolean: return "b";
            case SpecialType.System_SByte: return "c";
            case SpecialType.System_Byte: return "uc";
            case SpecialType.System_Int16: return "s";
            case SpecialType.System_UInt16: return "us";
            case SpecialType.System_Char: return "ch";
            case SpecialType.System_Object: return "o";
            case SpecialType.System_String: return "str";
        }
        if (t is IArrayTypeSymbol at) return ShortType(at.ElementType) + "A";
        if (t is ITypeParameterSymbol tp) return tp.Name;
        if (t is INamedTypeSymbol nt)
        {
            var s = nt.Name;
            if (nt.TypeArguments.Length > 0) s += string.Join("", nt.TypeArguments.Select(ShortType));
            return s;
        }
        return "x";
    }

    static string FieldIdent(IFieldSymbol f) => Id(f.Name);
    static string StripArity(string s) { var i = s.IndexOf('`'); return i < 0 ? s : s.Substring(0, i); }
}
